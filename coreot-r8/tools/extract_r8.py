"""Split the single-file CoreOT R8 prototype into the pieces this codebase uses.

    python tools/extract_r8.py path/to/CoreOT_R8_WebApp_Lite.html

Writes:
  frontend/css/app.css           the page's styles (fonts are served locally)
  frontend/vendor/jsqr.js        QR decoding library that was inlined in the page
  frontend/vendor/html-to-image.js  screenshot/export library that was inlined
  frontend/js/app.js             the application code, changed in exactly two places:
                                   1. `const DATA={...}` now reads the catalog the
                                      server sends (window.__R8_CATALOG)
                                   2. the final `render();` is removed; js/bridge.js
                                      starts the app once the server data is loaded
                                   3. the fixed user "Plant Admin" becomes the person
                                      who signed in (R8ME(), R8ROLE(), R8INI() in boot.js)
                                   4. before the Lite edition turns "+ Add" forms into
                                      "fields captured, not stored", the storing versions
                                      are kept (__saveAddStore, __coRecsStore) so the
                                      bridge can save those forms on the server
  frontend/index.html            the page markup, loading local copies of everything
  backend/app/seed/catalog.json  the catalog that was embedded in the page
                                 (icons, assets, readings, use cases, modules)

Run it again when a new version of the prototype arrives; nothing else needs editing
unless the new version changes how it stores data.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_PREFIX = "const DATA="
FINAL_RENDER = "\nrender();"


INDEX = """<!DOCTYPE html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{title}</title>
<link rel="icon" href="img/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="css/fonts.css">
<link rel="stylesheet" href="css/app.css">
<link rel="stylesheet" href="css/server.css">
<script src="vendor/three/three.min.js"></script>
<script src="vendor/three/OrbitControls.js"></script>
<script src="vendor/three/GLTFLoader.js"></script>
<script src="vendor/jsqr.js"></script>
<script src="vendor/html-to-image.js"></script>
</head>
<body>
<!-- generated by tools/extract_r8.py; the app starts from js/boot.js -->
<div id="r8-boot" class="r8-boot"><div class="r8-boot-card"><div class="logo"><i></i></div><b>Connecting to the plant server…</b><small id="r8-boot-msg"></small></div></div>
{body}
<script src="js/boot.js"></script>
</body></html>
"""


def scripts(html: str) -> list[str]:
    """Inline <script> bodies, in page order."""
    return [m.group(2) for m in re.finditer(r"<script([^>]*)>(.*?)</script>", html, re.S)
            if "src=" not in m.group(1)]


def personalise(app: str) -> str:
    """The prototype shows one fixed user. Show the signed-in person instead."""
    count = app.count("Plant Admin")
    app = app.replace("user:'Plant Admin',role:'Admin'", "user:R8ME(),role:R8ROLE()")
    app = app.replace("'Plant Admin'", "R8ME()")             # in code: by:'Plant Admin'
    app = app.replace('">PA</span>', '">${esc(R8INI())}</span>')  # avatar initials
    app = app.replace("admin@plantedge.in", "${esc(R8MAIL())}")
    app = app.replace("Plant Admin", "${esc(R8ME())}")       # in page templates
    if count and "R8ME()" not in app:
        sys.exit("Could not personalise the user name")
    return app


LITE_ADD = "/* ---------- + Add: fields only, nothing stored in the demo ---------- */"


def keep_storing_forms(app: str) -> str:
    if LITE_ADD not in app:
        print("note: the Lite '+ Add' override was not found; forms are stored as the app does")
        return app
    return app.replace(LITE_ADD, "const __saveAddStore=saveAdd,__coRecsStore=coRecs; /* kept for js/bridge.js */\n" + LITE_ADD, 1)


def split(html: str) -> dict[str, str]:
    style = re.search(r"<style>(.*?)</style>", html, re.S)
    if not style:
        sys.exit("No <style> block found")
    inline = scripts(html)
    if len(inline) != 3:
        sys.exit(f"Expected 3 inline scripts (jsQR, html-to-image, app), found {len(inline)}")
    jsqr, html_to_image, app = inline
    if "jsQR" not in jsqr or "htmlToImage" not in html_to_image:
        sys.exit("The inline libraries are not where they were expected")

    start = app.find(DATA_PREFIX)
    if start < 0:
        sys.exit("`const DATA=` not found in the app script")
    catalog, end = json.JSONDecoder().raw_decode(app, start + len(DATA_PREFIX))  # end: index after the JSON
    app = app[:start] + "const DATA=window.__R8_CATALOG" + app[end:]

    cut = app.rstrip().rfind(FINAL_RENDER.strip())
    if cut < 0 or app.rstrip()[cut:] != FINAL_RENDER.strip():
        sys.exit("The app script does not end with `render();`")
    app = app.rstrip()[:cut] + "/* render() is called by js/bridge.js once server data is loaded */\n"

    body = re.search(r"<body>(.*?)<script>", html, re.S)
    title = re.search(r"<title>(.*?)</title>", html, re.S)
    if not body:
        sys.exit("Could not find the page markup")
    index = INDEX.format(title=title.group(1) if title else "CoreOT R8", body=body.group(1).strip())

    app = personalise(app)
    app = keep_storing_forms(app)

    return {
        "frontend/index.html": index,
        "frontend/css/app.css": style.group(1).strip() + "\n",
        "frontend/vendor/jsqr.js": jsqr.strip() + "\n",
        "frontend/vendor/html-to-image.js": html_to_image.strip() + "\n",
        "frontend/js/app.js": "/* CoreOT R8 application code, extracted by tools/extract_r8.py. "
                              "Do not edit by hand. */\n" + app.lstrip(),
        "backend/app/seed/catalog.json": json.dumps(catalog, ensure_ascii=False, indent=1) + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("html", type=Path)
    args = parser.parse_args()
    for relative, content in split(args.html.read_text(encoding="utf-8")).items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {relative} ({len(content.encode()) // 1024} kB)")


if __name__ == "__main__":
    main()
